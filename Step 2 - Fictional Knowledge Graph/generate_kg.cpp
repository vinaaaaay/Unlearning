// ------------------------------- PRNG helpers ------------------------------
struct Rng {
    std::mt19937_64 eng;
    explicit Rng(uint64_t seed) : eng(seed) {}
    // Unbiased integer in [0, n) via rejection sampling (portable, unlike
    // std::uniform_int_distribution whose algorithm is implementation-defined).
    uint64_t below(uint64_t n) {
        assert(n > 0);
        const uint64_t limit = UINT64_MAX - (UINT64_MAX % n);  // largest multiple of n
        uint64_t x;
        do { x = eng(); } while (x >= limit);
        return x % n;
    }
};

std::vector<int> random_permutation(int n, Rng& rng, bool use_std_shuffle) {
    std::vector<int> p(n);
    for (int i = 0; i < n; ++i) p[i] = i;
    if (use_std_shuffle) {
        std::shuffle(p.begin(), p.end(), rng.eng);
    } else {
        for (int i = n - 1; i > 0; --i) {  // Fisher-Yates (Durstenfeld)
            int j = static_cast<int>(rng.below(static_cast<uint64_t>(i) + 1));
            std::swap(p[i], p[j]);
        }
    }
    return p;
}

// ------------------------------- formatting --------------------------------
std::string zpad(long v, int width) {
    std::ostringstream os;
    os << std::setw(width) << std::setfill('0') << v;
    return os.str();
}
std::string lower(std::string s) {
    for (char& c : s) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    return s;
}
std::string strip_spaces(const std::string& s) {
    std::string o;
    for (char c : s) if (c != ' ') o += c;
    return o;
}
std::string capitalize(std::string s) {
    if (!s.empty()) s[0] = static_cast<char>(std::toupper(static_cast<unsigned char>(s[0])));
    return s;
}

// ------------------------------- name synthesis ----------------------------
class NameFactory {
  public:
    explicit NameFactory(uint64_t seed) : rng_(seed) {
        for (const char* w : kLexicalBlocklist)
            if (w[0] != '\0') lexical_.insert(w);
    }
    size_t lexical_blocklist_size() const { return lexical_.size(); }
    size_t rejected_substring() const { return rej_substr_; }
    size_t rejected_lexical() const { return rej_lex_; }
    size_t rejected_duplicate() const { return rej_dup_; }

    bool blacklisted_substr(const std::string& lc) const {
        for (const auto& b : kSubstrBlacklist)
            if (lc.find(b) != std::string::npos) return true;
        return false;
    }
    bool lexical_hit(const std::string& lc) const { return lexical_.count(lc) > 0; }

    // Fresh, globally unique, filtered root (lower-case).
    std::string root() {
        for (int attempt = 0; attempt < 1000000; ++attempt) {
            std::string r;
            const auto& pick = [&](const std::vector<std::string>& v) -> const std::string& {
                return v[rng_.below(v.size())];
            };
            if (rng_.below(2) == 0) {  // Onset V Coda V Coda
                r = pick(kOnsets) + pick(kVowels) + pick(kCodas) + pick(kVowels) + pick(kCodas);
            } else {                   // Onset V Onset V Coda
                r = pick(kOnsets) + pick(kVowels) + pick(kOnsets) + pick(kVowels) + pick(kCodas);
            }
            if (blacklisted_substr(r)) { ++rej_substr_; continue; }
            if (lexical_hit(r)) { ++rej_lex_; continue; }
            if (!roots_.insert(r).second) { ++rej_dup_; continue; }
            return r;
        }
        std::cerr << "ERROR: root space exhausted; reduce --num-spines\n";
        std::exit(2);
    }

    std::string make(const std::string& type, int index_in_layer) {
        for (int attempt = 0; attempt < 100000; ++attempt) {
            std::string name;
            if (type == "Person") {
                name = capitalize(root()) + " " + capitalize(root());  // roots globally unique => distinct
            } else if (type == "Company") {
                name = capitalize(root()) + " " + kCompanySuffix[index_in_layer % kCompanySuffix.size()];
            } else {  // City
                name = capitalize(root() + kCitySuffix[index_in_layer % kCitySuffix.size()]);
            }
            const std::string lc = lower(strip_spaces(name));
            if (blacklisted_substr(lc)) { ++rej_substr_; continue; }       // cross-boundary substrings
            if (type == "City" && lexical_hit(lc)) { ++rej_lex_; continue; }
            if (!names_.insert(name).second) { ++rej_dup_; continue; }
            return name;
        }
        std::cerr << "ERROR: name space exhausted\n";
        std::exit(2);
    }

  private:
    Rng rng_;
    std::unordered_set<std::string> lexical_, roots_, names_;
    size_t rej_substr_ = 0, rej_lex_ = 0, rej_dup_ = 0;
};

