"""Regenerates the lexical blocklist embedded in generate_kg.cpp.

Enumerates every root the Sec. 3 grammar can produce (Onset V Coda V Coda and
Onset V Onset V Coda) plus every City name (root + city suffix), and blocks any
string that wordfreq attests in English with Zipf frequency >= THRESH (this
covers common words AND first names/surnames/place names, e.g. simon, lemon,
mason, nolan, brazil). Only needed when the grammar changes; the C++ program
itself stays dependency-free.  Usage: pip install wordfreq; python make_blocklist.py
"""
import itertools, re, wordfreq
THRESH = 1.0
O=["z","kr","v","tr","m","n","dr","pl","s","br","k","l","f","gl","th","p","d","r"]
V=list("aeiou"); C=list("lnrxsvkmtz"); CS=["ia","on","is","um","ar"]
roots=set()
for o,v1,c1,v2,c2 in itertools.product(O,V,C,V,C): roots.add(o+v1+c1+v2+c2)
for o,v1,o2,v2,c in itertools.product(O,V,O,V,C): roots.add(o+v1+o2+v2+c)
zf=lambda w: wordfreq.zipf_frequency(w,'en')
rb={r for r in roots if zf(r)>=THRESH}
cb={r+s for r in roots-rb for s in CS if zf(r+s)>=THRESH}
words=sorted(rb|cb)
body=["static const char* const kLexicalBlocklist[] = {"]
for i in range(0,len(words),10): body.append("    "+", ".join('"%s"'%w for w in words[i:i+10])+",")
body.append("};")
src=open("generate_kg.cpp").read()
src=re.sub(r"(// BEGIN LEXICAL BLOCKLIST\n).*?(// END LEXICAL BLOCKLIST)",
           lambda m: m.group(1)+"// AUTO-GENERATED by make_blocklist.py: wordfreq 'en', zipf >= %.1f; %d roots + %d city names.\n"%(THRESH,len(rb),len(cb))+"\n".join(body)+"\n"+m.group(2), src, flags=re.S)
open("generate_kg.cpp","w").write(src)
print(f"grammar roots={len(roots)} blocked roots={len(rb)} blocked city names={len(cb)}")
